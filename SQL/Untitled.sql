-- Get data as it existed 5 minutes ago
SELECT * FROM SNOWTRIP.PUBLIC.HELLOWORLD AT (OFFSET => -60*5);
-- Get deleted data using Time Travel (before the DELETE statement)
SELECT * FROM SNOWTRIP.PUBLIC.HELLOWORLD BEFORE (STATEMENT => LAST_QUERY_ID());

SELECT QUERY_ID, QUERY_TEXT, START_TIME
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY())
WHERE QUERY_TEXT ILIKE '%DELETE%HELLOWORLD%'
ORDER BY START_TIME DESC
LIMIT 5;