-- iNNER JOIN:- WILL GET THE COMMON VALUES FROM TWO OR MORE TABLES
SELECT F_TABLE.*,S_TABLE.*
FROM TABLE_A F_TABLE INNER JOIN TABLE_B S_TABLE
ON F_TABLE.ID=S_TABLE.ID;

-- LEFT JOIN: ALL RECORDS FROM LEFT TABLE AND COMMON RECORDS FROM RIGHT TABLE
SELECT F_TABLE.*,S_TABLE.*
FROM TABLE_A F_TABLE LEFT JOIN TABLE_B S_TABLE
ON F_TABLE.ID=S_TABLE.ID;

-- rIGHR JOIN: aLL RECORDS FORM RIGHT TABLE AND COMMON RECORDS FROM LEFT TABLE
SELECT F_TABLE.*,S_TABLE.*
FROM TABLE_A F_TABLE RIGHT JOIN TABLE_B S_TABLE
ON F_TABLE.ID=S_TABLE.ID;

-- WILL GET ALL RECORDS FORM TWO TABLES
SELECT F_TABLE.*,S_TABLE.*
FROM TABLE_A F_TABLE FULL JOIN TABLE_B S_TABLE
ON F_TABLE.ID=S_TABLE.ID;

